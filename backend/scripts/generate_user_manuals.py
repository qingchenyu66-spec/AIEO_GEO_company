def _title(doc: Document, text: str, subtitle: str = "") -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(22)
    run.font.color.rgb = RGBColor(0x1A, 0x36, 0x5D)
    if subtitle:
        sub = doc.add_paragraph(subtitle)
        sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
        sub.runs[0].font.size = Pt(11)
        sub.runs[0].font.color.rgb = RGBColor(0x66, 0x66, 0x66)
    doc.add_paragraph()


def _h1(doc: Document, text: str) -> None:
    doc.add_heading(text, level=1)


def _h2(doc: Document, text: str) -> None:
    doc.add_heading(text, level=2)


def _h3(doc: Document, text: str) -> None:
    doc.add_heading(text, level=3)


def _p(doc: Document, text: str) -> None:
    doc.add_paragraph(text)


def _note(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    run = p.add_run(f"【说明】{text}")
    run.italic = True


def _bullets(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def _numbered(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Number")


def _ui_item(doc: Document, name: str, desc: str) -> None:
    p = doc.add_paragraph(style="List Bullet")
    run = p.add_run(name)
    run.bold = True
    p.add_run(f"：{desc}")


def _page_section(
    doc: Document,
    menu_name: str,
    menu_path: str,
    page_intro: str,
    layout: list[tuple[str, list[tuple[str, str]]]],
    usage_steps: list[str] | None = None,
    tips: list[str] | None = None,
) -> None:
    _h1(doc, f"【{menu_name}】")
    _p(doc, f"侧边栏菜单名：{menu_name}")
    _p(doc, f"访问路径：{menu_path}")
    _p(doc, page_intro)
    doc.add_paragraph()
    for block_title, items in layout:
        _h2(doc, block_title)
        for name, desc in items:
            _ui_item(doc, name, desc)
        doc.add_paragraph()
    if usage_steps:
        _h2(doc, "怎么用（推荐步骤）")
        _numbered(doc, usage_steps)
    if tips:
        _h2(doc, "注意")
        _bullets(doc, tips)
    doc.add_paragraph()


def _footer(doc: Document) -> None:
    doc.add_paragraph()
    p = doc.add_paragraph(f"文档版本：{TODAY}　　内容以当前系统菜单配置为准")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for r in p.runs:
        r.font.size = Pt(9)
        r.font.color.rgb = RGBColor(0x99, 0x99, 0x99)


